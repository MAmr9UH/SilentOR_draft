import gurobipy as gp

def solve_model(data):
    # Create model
    model = gp.Model()

    # Define variables
    x = {}
    for i in range(len(data['distance'])):
        key = data['distance'].keys()[i]
        x[key] = model.addVar(vtype=gp.GRB.CONTINUOUS, name=key)

    y = {}
    for i in range(max([max(pair) for pair in data['pairs']]) + 1):
        y[i] = model.addVar(vtype=gp.GRB.BINARY, name=f"y_{i}")

    # Define objective function
    obj_func = gp.quicksum(data['distance'][key] * x[key] for key in x)
    model.setObjective(obj_func)

    # Define constraints
    for pair in data['pairs']:
        i, j = pair
        model.addConstr(x[f"{i},{j}"] + x[f"{j},{i}"] == 1)

    for i in range(max([max(pair) for pair in data['pairs']]) + 1):
        model.addConstr(gp.quicksum(x[f"{i},{j}"] for j in range(len(y)) if f"{i},{j}" in x) - y[i] <= 0)
        model.addConstr(gp.quicksum(x[f"{j},{i}"] for j in range(len(y)) if f"{j},{i}" in x) - y[i] <= 0)

    model.addConstr(gp.quicksum(y.values()) == len(data['pairs']))

    # Solve the model
    model.optimize()

    # Get solution status and objective value
    status = model.Status
    obj_val = model.ObjVal

    return {
        "status": status,
        "obj_val": obj_val,
        "variables": x,
        "y_variables": y
    }

